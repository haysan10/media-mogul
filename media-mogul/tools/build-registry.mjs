#!/usr/bin/env node
// build-registry.mjs — scan library/**/*.js and generate registry.js (+ registry.json when possible).
//   node tools/build-registry.mjs [projectDir]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(process.argv[2] ?? path.join(path.dirname(fileURLToPath(import.meta.url)), '..'));
const libDir = path.join(root, 'library');

function walk(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) return walk(p);
    return e.name.endsWith('.js') ? [p] : [];
  });
}

const files = walk(libDir).sort();
const rel = (f) => './' + path.relative(root, f).split(path.sep).join('/');

let out = '// AUTO-GENERATED by tools/build-registry.mjs — do not edit. Run `npm run registry` after adding assets.\n';
files.forEach((f, i) => (out += `import * as a${i} from '${rel(f)}';\n`));
out += `
export const registry = [${files.map((_, i) => `a${i}`).join(', ')}].map((m) => ({ meta: m.meta, create: m.create }));
export const byId = Object.fromEntries(registry.map((a) => [a.meta.id, a]));

/** create(id, options) => THREE.Group */
export function create(id, options) {
  const a = byId[id];
  if (!a) throw new Error('Unknown asset id: ' + id + '. Available: ' + Object.keys(byId).join(', '));
  return a.create(options);
}

export default registry;
`;
fs.writeFileSync(path.join(root, 'registry.js'), out);

// metadata json (needs `three` installed because assets import it)
const metas = [];
const seen = new Map();
let jsonOk = true;
for (const f of files) {
  try {
    const m = await import(pathToFileURL(f).href);
    if (!m.meta?.id) throw new Error('missing exported `meta.id`');
    if (seen.has(m.meta.id)) {
      console.error(`✗ duplicate asset id "${m.meta.id}" in ${rel(f)} and ${seen.get(m.meta.id)}`);
      process.exitCode = 1;
    }
    seen.set(m.meta.id, rel(f));
    metas.push({ ...m.meta, file: rel(f) });
  } catch (err) {
    jsonOk = false;
    if (!(err.code === 'ERR_MODULE_NOT_FOUND' && /'three'/.test(err.message))) {
      console.warn(`! could not read meta from ${rel(f)}: ${err.message}`);
    }
    break;
  }
}
if (jsonOk) fs.writeFileSync(path.join(root, 'registry.json'), JSON.stringify(metas, null, 2) + '\n');

console.log(`✓ registry.js — ${files.length} asset(s)${jsonOk ? ' + registry.json' : ' (registry.json skipped: run npm install first)'}`);
